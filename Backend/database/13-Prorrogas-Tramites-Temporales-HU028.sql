-- HU-028: historial de prórrogas autorizadas para trámites temporales.
-- Migración incremental; no modifica ni elimina información existente.
-- Ejecutar después de 06-Tablas-Tramites-Temporales.sql con el cliente de MySQL.
SET NAMES utf8mb4;

USE sim;

CREATE TABLE IF NOT EXISTS SIMT_HISTORIAL_PRORROGA_TEMPORAL (
    ID_HISTORIAL_PRORROGA   INT             NOT NULL AUTO_INCREMENT,
    ID_TRAMITE              INT             NOT NULL,
    FECHA_VENCIMIENTO_ANTERIOR DATE          NOT NULL,
    FECHA_VENCIMIENTO_NUEVA DATE            NOT NULL,
    MOTIVO                  VARCHAR(500)    NOT NULL,
    OFICIO_SOLICITUD        VARCHAR(120)    NOT NULL,
    NUMERO_GESTION          VARCHAR(80)     NOT NULL,
    NUMERO_AUTORIZACION     VARCHAR(120)    NOT NULL,
    NUMERO_CONTRATO         VARCHAR(120)    NULL,
    ID_DOCUMENTO_OFICIO     INT             NOT NULL,
    ID_DOCUMENTO_RESOLUCION INT             NOT NULL,
    ID_USUARIO_REGISTRO     INT             NOT NULL,
    FECHA_REGISTRO          DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SIMT_HISTORIAL_PRORROGA_TEMPORAL PRIMARY KEY (ID_HISTORIAL_PRORROGA),
    CONSTRAINT FK_SIMT_HISTORIAL_PRORROGA_TRAMITE
        FOREIGN KEY (ID_TRAMITE) REFERENCES SIMT_TRAMITE (ID_TRAMITE),
    CONSTRAINT FK_SIMT_HISTORIAL_PRORROGA_OFICIO
        FOREIGN KEY (ID_DOCUMENTO_OFICIO) REFERENCES SIMF_DOCUMENTO (ID_DOCUMENTO),
    CONSTRAINT FK_SIMT_HISTORIAL_PRORROGA_RESOLUCION
        FOREIGN KEY (ID_DOCUMENTO_RESOLUCION) REFERENCES SIMF_DOCUMENTO (ID_DOCUMENTO),
    CONSTRAINT FK_SIMT_HISTORIAL_PRORROGA_USUARIO
        FOREIGN KEY (ID_USUARIO_REGISTRO) REFERENCES SIMF_USUARIO (ID_USUARIO),
    INDEX IDX_SIMT_HISTORIAL_PRORROGA_TRAMITE (ID_TRAMITE),
    CONSTRAINT UK_SIMT_HISTORIAL_PRORROGA_OFICIO UNIQUE (ID_DOCUMENTO_OFICIO),
    CONSTRAINT UK_SIMT_HISTORIAL_PRORROGA_RESOLUCION UNIQUE (ID_DOCUMENTO_RESOLUCION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Historial de prórrogas autorizadas de trámites temporales (HU-028).';
