SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS sim
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE sim;

CREATE TABLE IF NOT EXISTS SIMM_ROL (
    ID_ROL       BIGINT        NOT NULL AUTO_INCREMENT,
    NOMBRE       VARCHAR(50)   NOT NULL,
    DESCRIPCION  VARCHAR(255)  NULL,
    ESTADO       CHAR(3)       NOT NULL DEFAULT 'ACT',
    TIME_STAMP   DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT PK_SIMM_ROL PRIMARY KEY (ID_ROL),
    CONSTRAINT AK_SIMM_ROL_NOMBRE UNIQUE (NOMBRE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SIMM_PERMISO (
    ID_PERMISO   BIGINT        NOT NULL AUTO_INCREMENT,
    CODIGO       VARCHAR(60)   NOT NULL,
    NOMBRE       VARCHAR(100)  NOT NULL,
    DESCRIPCION  VARCHAR(255)  NULL,
    ESTADO       CHAR(3)       NOT NULL DEFAULT 'ACT',
    TIME_STAMP   DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT PK_SIMM_PERMISO PRIMARY KEY (ID_PERMISO),
    CONSTRAINT AK_SIMM_PERMISO_CODIGO UNIQUE (CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SIMT_USUARIO_ROL (
    ID_USUARIO_ROL          BIGINT        NOT NULL AUTO_INCREMENT,
    ID_USUARIO              INT           NOT NULL,
    ID_ROL                  BIGINT        NOT NULL,
    ID_USUARIO_ASIGNADOR    INT           NOT NULL,
    ID_USUARIO_FINALIZADOR  INT           NULL,
    FECHA_ASIGNACION        DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    FECHA_FINALIZACION      DATETIME(6)   NULL,
    MOTIVO                  VARCHAR(255)  NULL,
    ESTADO                  CHAR(3)       NOT NULL DEFAULT 'ACT',
    CONSTRAINT PK_SIMT_USUARIO_ROL PRIMARY KEY (ID_USUARIO_ROL),
    CONSTRAINT FK_SIMT_USUARIO_ROL_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES SIMF_USUARIO (ID_USUARIO),
    CONSTRAINT FK_SIMT_USUARIO_ROL_ASIGNADOR
        FOREIGN KEY (ID_USUARIO_ASIGNADOR) REFERENCES SIMF_USUARIO (ID_USUARIO),
    CONSTRAINT FK_SIMT_USUARIO_ROL_FINALIZADOR
        FOREIGN KEY (ID_USUARIO_FINALIZADOR) REFERENCES SIMF_USUARIO (ID_USUARIO),
    CONSTRAINT FK_SIMT_USUARIO_ROL_ROL
        FOREIGN KEY (ID_ROL) REFERENCES SIMM_ROL (ID_ROL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SIMT_ROL_PERMISO (
    ID_ROL_PERMISO  BIGINT       NOT NULL AUTO_INCREMENT,
    ID_ROL          BIGINT       NOT NULL,
    ID_PERMISO      BIGINT       NOT NULL,
    FECHA_ASIGNACION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    ESTADO          CHAR(3)      NOT NULL DEFAULT 'ACT',
    CONSTRAINT PK_SIMT_ROL_PERMISO PRIMARY KEY (ID_ROL_PERMISO),
    CONSTRAINT FK_SIMT_ROL_PERMISO_ROL
        FOREIGN KEY (ID_ROL) REFERENCES SIMM_ROL (ID_ROL),
    CONSTRAINT FK_SIMT_ROL_PERMISO_PERMISO
        FOREIGN KEY (ID_PERMISO) REFERENCES SIMM_PERMISO (ID_PERMISO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SIT_SESION (
    ID_SESION         BIGINT        NOT NULL AUTO_INCREMENT,
    ID_USUARIO        INT           NOT NULL,
    TOKEN_HASH        VARCHAR(255)  NOT NULL,
    FECHA_CREACION    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHA_EXPIRACION  DATETIME      NOT NULL,
    ES_ACTIVA         TINYINT       NOT NULL DEFAULT 1,
    CONSTRAINT PK_SIT_SESION PRIMARY KEY (ID_SESION),
    CONSTRAINT AK_SIT_SESION_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_SIT_SESION_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES SIMF_USUARIO (ID_USUARIO),
    INDEX IDX_SIT_SESION_USUARIO_ACTIVA (ID_USUARIO, ES_ACTIVA, FECHA_EXPIRACION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
