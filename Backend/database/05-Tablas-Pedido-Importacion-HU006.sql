-- HU-006: detalle de solicitudes de importación (pedido a proveedor).
-- Ejecutar después de 02-Tablas-Tramites.sql y 03-Datos-Iniciales.sql.
SET NAMES utf8mb4;
USE sim;

CREATE TABLE IF NOT EXISTS SIMM_OPCION_IMPORTACION (
    ID_OPCION       INT             NOT NULL AUTO_INCREMENT,
    TIPO_OPCION     VARCHAR(20)     NOT NULL,
    VALOR           VARCHAR(160)    NOT NULL,
    ESTADO          CHAR(3)         NOT NULL DEFAULT 'ACT',
    TIME_STAMP      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT PK_SIMM_OPCION_IMPORTACION PRIMARY KEY (ID_OPCION),
    CONSTRAINT AK_SIMM_OPCION_IMPORTACION UNIQUE (TIPO_OPCION, VALOR),
    CONSTRAINT CK_ESTADO_OPCION_IMPORTACION CHECK (ESTADO IN ('ACT', 'INA'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Opciones de importación guardadas para reutilizar unidades, compañías, incoterms y monedas.';

CREATE TABLE IF NOT EXISTS SIMT_PEDIDO_PROV (
    ID_TRAMITE                       INT             NOT NULL,
    CANTIDAD_SOLICITADA              DECIMAL(13,3)   NULL,
    FECHA_RECIBIDO_EXPEDIENTE        DATE            NOT NULL,
    UNIDAD_SOLICITANTE               VARCHAR(120)    NOT NULL,
    DESCRIPCION_SOLICITUD            TEXT            NOT NULL,
    NUMERO_CONTRATACION              VARCHAR(100)    NOT NULL,
    NUMERO_PEDIDO                    VARCHAR(20)     NOT NULL,
    COMPANIA_ADJUDICADA              VARCHAR(160)    NOT NULL,
    NUMERO_ORDEN_COMPRA              VARCHAR(20)     NOT NULL,
    INCOTERM                         VARCHAR(10)     NULL,
    PRESUPUESTO_ORDEN_CRC            DECIMAL(15,2)   NULL,
    MONTO_ORDEN                      DECIMAL(18,2)   NULL,
    MONEDA_ORDEN                     VARCHAR(30)     NOT NULL DEFAULT 'CRC',
    SALDO_DISPONIBLE                 DECIMAL(18,2)   NULL,
    FECHA_RECIBIDO_SP_OAF            DATE            NULL,
    FECHA_RECIBIDO_COPIA_CHEQUE_UI   DATE            NULL,
    FECHA_TRANSFERENCIA              DATE            NULL,
    FECHA_ESTIMADA_DESPACHO          DATE            NULL,
    FECHA_INGRESO_PAIS               DATE            NULL,
    FECHA_DESALMACENAJE              DATE            NULL,
    FACTURA                          VARCHAR(100)    NULL,
    PARTIDA                          SMALLINT        NULL,
    PARTIDA_2                        SMALLINT        NULL,
    MONTO_CANCELADO_CRC              DECIMAL(15,2)   NULL,
    SOBRANTE_FALTANTE_CRC            DECIMAL(15,2)   NULL,
    RECLAMO                          VARCHAR(2000)   NULL,
    TIME_STAMP                       TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT PK_SIMT_PEDIDO_PROV PRIMARY KEY (ID_TRAMITE),
    CONSTRAINT FK_SIMT_TRAMITE_SIMT_PEDIDO_PROV
        FOREIGN KEY (ID_TRAMITE) REFERENCES SIMT_TRAMITE (ID_TRAMITE),
    CONSTRAINT CK_CANTIDAD_PEDIDO_POSITIVA CHECK (CANTIDAD_SOLICITADA > 0),
    CONSTRAINT CK_PRESUPUESTO_PEDIDO_CRC CHECK (
        PRESUPUESTO_ORDEN_CRC IS NULL OR PRESUPUESTO_ORDEN_CRC BETWEEN 0 AND 50000000
    ),
    CONSTRAINT CK_PARTIDA_PEDIDO_PROV CHECK (PARTIDA IS NULL OR PARTIDA IN (1, 2, 5)),
    CONSTRAINT CK_PARTIDA_2_PEDIDO_PROV CHECK (PARTIDA_2 IS NULL OR PARTIDA_2 IN (1, 2, 5)),
    CONSTRAINT CK_MONTO_ORDEN_PEDIDO CHECK (MONTO_ORDEN IS NULL OR MONTO_ORDEN >= 0),
    CONSTRAINT CK_SALDO_PEDIDO_PROV CHECK (SALDO_DISPONIBLE IS NULL OR SALDO_DISPONIBLE >= 0),
    CONSTRAINT CK_MONTO_CANCELADO_PEDIDO CHECK (MONTO_CANCELADO_CRC IS NULL OR MONTO_CANCELADO_CRC >= 0),
    KEY IDX_SIMT_PEDIDO_PROV_FECHA_TRANSFERENCIA (FECHA_TRANSFERENCIA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Datos propios de la solicitud de importación. Comparte la llave primaria con SIMT_TRAMITE.';

-- CATEGORIA_ESTADO (HU-034): el estado inicial del pedido es pendiente de ingreso (PEN).
-- La Unidad lo llama "Pendiente de pago" (pago ante la OAF). El resto del catálogo de estados
-- del pedido lo agrega 15-Ajustes-Comentarios-Unidad.sql.
INSERT INTO SIMM_ESTADO_TRAMITE (ID_TIPO_TRAMITE, NOMBRE, ES_INICIAL, ES_FINAL, CATEGORIA_ESTADO, ORDEN)
SELECT t.ID_TIPO_TRAMITE, 'Pendiente de pago', 1, 0, 'PEN', 1
FROM SIMM_TIPO_TRAMITE t
WHERE t.CODIGO = 'PEDIDO_PROV'
  AND NOT EXISTS (
      SELECT 1
      FROM SIMM_ESTADO_TRAMITE e
      WHERE e.ID_TIPO_TRAMITE = t.ID_TIPO_TRAMITE
        AND UPPER(e.NOMBRE) IN ('PENDIENTE', 'PENDIENTE DE PAGO')
  );
